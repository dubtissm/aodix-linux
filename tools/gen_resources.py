#!/usr/bin/env python3
# Embeds small binary resources (icon, cursors) into a C header.
import sys, os
out = sys.argv[1]
with open(out, 'w') as f:
    f.write('// generated by tools/gen_resources.py\n#pragma once\n')
    for path in sys.argv[2:]:
        name = 'res_' + os.path.basename(path).replace('.', '_')
        data = open(path, 'rb').read()
        f.write('static const unsigned char %s[%d]={\n' % (name, len(data)))
        for i in range(0, len(data), 32):
            f.write('\t' + ','.join(str(b) for b in data[i:i+32]) + ',\n')
        f.write('};\n')
