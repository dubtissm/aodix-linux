#!/usr/bin/env python3
# Extracts the 6x8 "Terminal"-style glyphs from the Aodix skin font strip (gfx.bmp, y=588)
# and writes them as a C header (one byte per glyph row, bit 5 = leftmost pixel).
import sys
from PIL import Image
from collections import Counter
src, dst = sys.argv[1], sys.argv[2]
im = Image.open(src).convert('RGB')
y0 = 588
rows = []
bg = Counter(im.getpixel((x, y)) for x in range(0, 768) for y in range(y0, y0+8)).most_common(1)[0][0]
for ch in range(128):
    glyph = []
    for y in range(8):
        bits = 0
        for x in range(6):
            p = im.getpixel((ch*6+x, y0+y))
            if p != bg:
                bits |= 1 << (5-x)
        glyph.append(bits)
    rows.append(glyph)
with open(dst, 'w') as f:
    f.write('// generated by tools/gen_terminal_font.py from the Aodix skin font strip\n')
    f.write('#pragma once\nstatic const unsigned char adx_terminal_font_6x8[128][8]={\n')
    for ch, g in enumerate(rows):
        f.write('\t{%s}, // %d %s\n' % (','.join('0x%02X' % b for b in g), ch, repr(chr(ch)) if 32 <= ch < 127 else ''))
    f.write('};\n')
