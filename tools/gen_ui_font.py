#!/usr/bin/env python3
# Rasterizes a UI font (used for menus, dialogs and message boxes - the Windows "Tahoma 8" role)
# into an 8-bit alpha atlas and writes it as a C header. Default font: DejaVu Sans Condensed 11px.
import sys
from PIL import ImageFont
out = sys.argv[1]
regular = sys.argv[2] if len(sys.argv) > 2 else '/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed.ttf'
bold = sys.argv[3] if len(sys.argv) > 3 else '/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf'
# (name, path, pixel size); 'small' is used automatically for labels that would not fit their control
faces = [('regular', regular, 11), ('bold', bold, 11), ('small', regular, 10)]
with open(out, 'w') as f:
    f.write('// generated by tools/gen_ui_font.py (DejaVu Sans Condensed, 11px; DejaVu fonts license: Bitstream Vera / public domain changes)\n#pragma once\n')
    f.write('struct ADX_UI_GLYPH { short adv, x, y, w, h; int ofs; };\n')
    for name, path, size in faces:
        ft = ImageFont.truetype(path, size)
        ascent, descent = ft.getmetrics()
        data = bytearray(); glyphs = []
        for cp in range(256):
            if cp < 32 or 127 <= cp < 160:
                glyphs.append((0, 0, 0, 0, 0, 0)); continue
            ch = chr(cp)
            adv = int(round(ft.getlength(ch)))
            mask, offset = ft.getmask2(ch, mode='L')
            w, h = mask.size
            ofs = len(data)
            data += bytes(mask)
            # y relative to baseline-top (ascent line)
            glyphs.append((adv, offset[0], offset[1], w, h, ofs))
        f.write('static const int adx_ui_font_%s_ascent=%d, adx_ui_font_%s_height=%d;\n' % (name, ascent, name, ascent + descent))
        f.write('static const ADX_UI_GLYPH adx_ui_font_%s_glyphs[256]={\n' % name)
        for g in glyphs:
            f.write('\t{%d,%d,%d,%d,%d,%d},\n' % g)
        f.write('};\nstatic const unsigned char adx_ui_font_%s_data[%d]={\n' % (name, max(1, len(data))))
        for i in range(0, len(data), 32):
            f.write('\t' + ','.join(str(b) for b in data[i:i+32]) + ',\n')
        f.write('};\n')
